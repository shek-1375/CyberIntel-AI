"""The investigation workflow as a LangGraph state graph.

                      START
                        │
                ┌───────▼────────┐
                │extract_entities│   regex: CVE and ATT&CK IDs
                └───────┬────────┘
            CVEs found? │ (conditional edge)
             yes ┌──────┴───────┐ no
                 ▼              │
          ┌────────────┐        │
          │enrich_cves │        │   NVD + CISA KEV + EPSS + ATT&CK suggestions
          └─────┬──────┘        │
                ▼               ▼
            ┌────────────────────┐
            │ retrieve_evidence  │   RAG over our documents (query expanded)
            └─────────┬──────────┘
            ┌─────────▼──────────┐
            │     map_attack     │   candidates by code -> Gemini picks -> validated
            └─────────┬──────────┘
            ┌─────────▼──────────┐
            │     recommend      │   rule-based risk + Gemini plan, every item cites a basis
            └─────────┬──────────┘
            ┌─────────▼──────────┐
            │    write_report    │   LLM summary + tables rendered by code
            └─────────┬──────────┘
                     END

Why a graph rather than one big prompt? Each step is small, testable and
inspectable (`steps` shows what happened and how long it took), tools are
called only when needed (the conditional edge), and a failure in one node is
recorded without stopping the rest.
"""
from functools import lru_cache

from app.agent import nodes
from app.agent.state import InvestigationState


def build_graph():
    from langgraph.graph import END, START, StateGraph

    g = StateGraph(InvestigationState)
    g.add_node("extract_entities", nodes.extract_entities)
    g.add_node("enrich_cves", nodes.enrich_cves)
    g.add_node("retrieve_evidence", nodes.retrieve_evidence)
    g.add_node("map_attack", nodes.map_attack)
    g.add_node("recommend", nodes.recommend)
    g.add_node("write_report", nodes.write_report)

    g.add_edge(START, "extract_entities")
    g.add_conditional_edges(
        "extract_entities",
        nodes.route_after_entities,
        {"enrich_cves": "enrich_cves", "retrieve_evidence": "retrieve_evidence"},
    )
    g.add_edge("enrich_cves", "retrieve_evidence")
    g.add_edge("retrieve_evidence", "map_attack")
    g.add_edge("map_attack", "recommend")
    g.add_edge("recommend", "write_report")
    g.add_edge("write_report", END)
    return g.compile()


@lru_cache(maxsize=1)
def get_graph():
    return build_graph()


def run_investigation(query: str) -> dict:
    final = get_graph().invoke({"query": query, "steps": [], "errors": []})
    return {
        "query": query,
        "risk": final.get("risk"),
        "summary": final.get("summary"),
        "cves": [
            {"cve_id": c["cve_id"], "priority": c["priority"], "kev": c.get("kev"), "epss": c.get("epss"),
             "cvss": ((c.get("nvd") or {}).get("cvss")), "description": (c.get("nvd") or {}).get("description")}
            for c in final.get("cve_cards", [])
        ],
        "attack_mapping": final.get("attack_mapping", []),
        "recommendations": final.get("recommendations", []),
        "evidence": [{"ref": e["ref"], "source": e["source"], "snippet": e["text"][:300]} for e in final.get("evidence", [])],
        "steps": final.get("steps", []),
        "errors": final.get("errors", []),
        "report_markdown": final.get("report_markdown", ""),
    }


def graph_mermaid() -> str:
    """Mermaid diagram of the compiled graph, generated by LangGraph itself."""
    return get_graph().get_graph().draw_mermaid()
